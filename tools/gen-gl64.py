#!/usr/bin/env python3
"""Generates src/loader/win64/gl64Wrappers.h from glad's gl.h: a System V
entry point for each GL function (the 64-bit Linux games call with the System V
ABI, Windows' GL with its own), and their table (name, wrapper, real pointer).

Usage: tools/gen-gl64.py [src/glad/include/glad/gl.h] > src/loader/win64/gl64Wrappers.h
"""
import re
import sys

src = sys.argv[1] if len(sys.argv) > 1 else "src/glad/include/glad/gl.h"
text = open(src).read()
proto = re.compile(r"typedef (.+?) \(GLAD_API_PTR \*PFN(GL\w+)PROC\)\((.*?)\);")

out = ["// Generated by tools/gen-gl64.py from glad's gl.h: do not edit.", ""]
table = []
for ret, upper, args in proto.findall(text):
    # The function's name, with glad's own case.
    names = re.findall(r"GLAD_API_CALL PFN" + upper + r"PROC glad_(gl\w+);", text)
    if not names:
        continue
    name = names[0]
    params = [] if args.strip() in ("", "void") else [a.strip() for a in args.split(",")]
    argNames = []
    decl = []
    for i, p in enumerate(params):
        # Callbacks (debug messages) are the game's System V functions: kept
        # as they are, the driver cannot call them.
        mm = re.match(r"(.*?)(\w+)((?:\s*\[\d*\])*)$", p)
        if not mm:
            decl.append(p + " a%d" % i)
            argNames.append("a%d" % i)
            continue
        typ, var, arr = mm.groups()
        if not typ.strip():
            decl.append("%s a%d" % (p, i))
            argNames.append("a%d" % i)
            continue
        decl.append(p)
        argNames.append(var)
    retKw = "" if ret.strip() == "void" else "return "
    out.append("static PFN%sPROC r_%s;" % (upper, name))
    out.append("static unsigned n_%s;" % name)
    out.append("static SYSV %s w_%s(%s) { n_%s++; %sr_%s(%s); }" % (
        ret, name, ", ".join(decl) if decl else "void", name, retKw, name, ", ".join(argNames)))
    table.append(name)

out.append("")
out.append("static const struct { const char *name; void *wrapper; void **real; unsigned *calls; } glFunctions[] = {")
for n in table:
    out.append('    {"%s", (void *)w_%s, (void **)&r_%s, &n_%s},' % (n, n, n, n))
out.append("};")
print("\n".join(out))
